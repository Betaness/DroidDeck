#!/bin/sh
# Regenerates mali_quirks_spv.h from mq_*.spvasm, mq_quad.vert and mq_white.frag (spirv-as, glslangValidator).
set -eu
cd "$(dirname "$0")"
t=$(mktemp -d)
spirv-as --target-env vulkan1.1 mq_spec.spvasm -o $t/spec.spv
spirv-as --target-env vulkan1.1 mq_bound.spvasm -o $t/bound.spv
glslangValidator -V --target-env vulkan1.1 mq_quad.vert -o $t/quad.spv >/dev/null
glslangValidator -V --target-env vulkan1.1 mq_white.frag -o $t/white.spv >/dev/null
{
  echo "/* Generated by mq_gen.sh from mq_spec.spvasm, mq_bound.spvasm, mq_quad.vert and mq_white.frag. */"
  echo "#pragma once"
  for n in spec bound quad white; do
    echo "static const uint32_t mq_${n}_spv[] = {"
    od -An -v -tx4 -w32 $t/$n.spv | sed 's/ \([0-9a-f]\{8\}\)/0x\1,/g; s/^/   /'
    echo "};"
  done
} > mali_quirks_spv.h
rm -rf $t
