#!/usr/bin/env python3
"""Lists, for tests/reply_fault_test.c, every extension structure the serializer carries in the
pNext chains of the replies the client unserialises (VkPhysicalDeviceProperties2,
VkPhysicalDeviceFeatures2, ...), as a C header:

  reply_fault_gen.py <work/vortek/include/vortek_serializer.h> > out/reply_fault_chains.h
"""
import re
import sys

PARENTS = [
    "VkPhysicalDeviceProperties2",
    "VkPhysicalDeviceFeatures2",
    "VkPhysicalDeviceMemoryProperties2",
    "VkFormatProperties2",
    "VkImageFormatProperties2",
    "VkMemoryRequirements2",
    "VkQueueFamilyProperties2",
    "VkSurfaceCapabilities2KHR",
]


def main():
    src = open(sys.argv[1]).read()
    print("/* Generated by tests/reply_fault_gen.py from the patched vortek_serializer.h. */")
    print("typedef struct ChainEntry { VkStructureType sType; const char* name; } ChainEntry;")
    for parent in PARENTS:
        m = re.search(r"^static inline int vt_sizeof_%s\(.*?\) \{\n(.*?)^\}" % parent, src, re.S | re.M)
        cases = []
        if m:
            for c in re.finditer(r"case (VK_STRUCTURE_TYPE_\w+): \{\s*bufferSize \+= 4;\s*bufferSize \+= vt_sizeof_(\w+)\(", m.group(1)):
                cases.append((c.group(1), c.group(2)))
        print("static const ChainEntry chain_%s[] = {" % parent)
        for stype, name in cases:
            print('    {%s, "%s"},' % (stype, name))
        print("    {0, NULL}\n};")


if __name__ == "__main__":
    main()
