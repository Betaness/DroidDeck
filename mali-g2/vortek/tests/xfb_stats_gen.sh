#!/bin/sh
# Regenerates xfb_stats_spv.h from xfb.vert, xfb_plain.vert and xfb.geom (glslangValidator).
set -eu
cd "$(dirname "$0")"
T=$(mktemp -d)
glslangValidator -V --target-env vulkan1.1 --vn xfb_vert_spv -o "$T/a.h" xfb.vert >/dev/null
glslangValidator -V --target-env vulkan1.1 --vn xfb_plain_vert_spv -o "$T/b.h" xfb_plain.vert >/dev/null
glslangValidator -V --target-env vulkan1.1 --vn xfb_geom_spv -o "$T/c.h" xfb.geom >/dev/null
{ echo "/* Generated by xfb_stats_gen.sh from xfb.vert, xfb_plain.vert and xfb.geom. */"; cat "$T/a.h" "$T/b.h" "$T/c.h"; } > xfb_stats_spv.h
rm -rf "$T"
