#!/usr/bin/env python3
"""Generate src/ext_commands.h: for every device extension in vk.xml, the commands it adds.

The Vortek client uses it to stop advertising device extensions whose commands it does not
implement (the loader aborts when an app calls such a command; Steam's webhelper did this with
VK_KHR_fragment_shading_rate). Usage: gen_ext_commands.py vk.xml > src/ext_commands.h
"""
import sys
import xml.etree.ElementTree as ET

root = ET.parse(sys.argv[1]).getroot()
aliases = {}
for c in root.iter("command"):
    if c.get("alias"):
        aliases[c.get("name")] = c.get("alias")
rows = []
for ext in root.iter("extension"):
    if ext.get("type") != "device" or "vulkan" not in (ext.get("supported") or "").split(","):
        continue
    cmds = []
    for req in ext.iter("require"):
        # Commands that only exist together with another extension do not decide support.
        if req.get("depends"):
            continue
        for c in req.iter("command"):
            n = c.get("name")
            if n not in cmds:
                cmds.append(n)
    if cmds:
        rows.append((ext.get("name"), cmds))
print("/* Generated by tools/gen_ext_commands.py from vk.xml - do not edit. */")
print("#pragma once")
print("typedef struct { const char* extension; const char* const* commands; } VtExtCommands;")
for i, (name, cmds) in enumerate(rows):
    print("static const char* const vt_ext_cmds_%d[] = {%s, 0};" % (i, ", ".join('"%s"' % c for c in cmds)))
print("static const VtExtCommands vt_ext_commands[] = {")
for i, (name, _) in enumerate(rows):
    print('    {"%s", vt_ext_cmds_%d},' % (name, i))
print("};")
