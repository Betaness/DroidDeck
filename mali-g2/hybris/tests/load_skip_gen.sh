#!/bin/sh
# Regenerates load_skip_spv.h, the shaders of load_skip_test.c (glslangValidator; spirv-opt and
# python3 for the ones taken to SSA form as DXVK's are).
set -eu
cd "$(dirname "$0")"
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
echo "/* Generated by load_skip_gen.sh. */" > "$T/all.h"
shader() { # name stage [ssa]
    cat > "$T/$1.$2"
    if [ "${3:-}" = ssa ]; then
        glslangValidator -V --target-env vulkan1.1 -o "$T/$1.spv" "$T/$1.$2" >/dev/null
        spirv-opt --ssa-rewrite "$T/$1.spv" -o "$T/$1.ssa.spv"
        python3 -c 'import struct,sys
w=open(sys.argv[1],"rb").read()
w=struct.unpack("<%dI"%(len(w)//4),w)
print("const uint32_t ls_%s[] = {"%sys.argv[2])
for i in range(0,len(w),8): print("\t"+",".join("0x%08x"%x for x in w[i:i+8])+",")
print("};")' "$T/$1.ssa.spv" "$1" >> "$T/all.h"
        return
    fi
    glslangValidator -V --target-env vulkan1.1 --vn "ls_$1" -o "$T/$1.h" "$T/$1.$2" >/dev/null
    grep -v '^\s*//\|#pragma once' "$T/$1.h" >> "$T/all.h"
}
# position and texture coordinate passed through
shader vs_pass vert <<'GLSL'
#version 450
layout(location = 0) in vec4 position;
layout(location = 1) in vec2 uv;
layout(location = 0) out vec2 outUv;
void main() { gl_Position = position; outUv = uv; }
GLSL
# a full-screen triangle from the vertex index, through a function and a loop
shader vs_tri vert <<'GLSL'
#version 450
layout(location = 0) out vec2 outUv;
vec2 corner(int i) {
    vec2 p = vec2(0.0);
    for (int k = 0; k < 2; k++) p[k] = float((i >> (1 - k)) & 1) * 4.0 - 1.0;
    return p.yx;
}
void main() {
    vec2 p = corner(gl_VertexIndex == 0 ? 0 : gl_VertexIndex == 1 ? 2 : 1);
    gl_Position = vec4(p, 0.0, 1.0);
    outUv = p * 0.5 + 0.5;
}
GLSL
# the position moved by a uniform: not known on the CPU
shader vs_ubo vert <<'GLSL'
#version 450
layout(location = 0) in vec4 position;
layout(location = 1) in vec2 uv;
layout(binding = 0) uniform Offset { vec4 offset; };
layout(location = 0) out vec2 outUv;
void main() { gl_Position = position + offset; outUv = uv; }
GLSL
# a clip distance negative at the left vertices
shader vs_clip vert <<'GLSL'
#version 450
layout(location = 0) in vec4 position;
layout(location = 1) in vec2 uv;
layout(location = 0) out vec2 outUv;
out float gl_ClipDistance[1];
void main() { gl_Position = position; gl_ClipDistance[0] = position.x; outUv = uv; }
GLSL
# scaled by a specialization constant
shader vs_spec vert <<'GLSL'
#version 450
layout(constant_id = 3) const float scale = 1.0;
layout(location = 0) in vec4 position;
layout(location = 1) in vec2 uv;
layout(location = 0) out vec2 outUv;
void main() { gl_Position = vec4(position.xy * scale, position.zw); outUv = uv; }
GLSL
# moved by push constants (at byte 16)
shader vs_push vert <<'GLSL'
#version 450
layout(location = 0) in vec4 position;
layout(location = 1) in vec2 uv;
layout(push_constant) uniform Push { layout(offset = 16) vec4 offset; };
layout(location = 0) out vec2 outUv;
void main() { gl_Position = position + offset; outUv = uv; }
GLSL
# row- and column-major matrices from a uniform buffer, chosen by an integer read from it
shader vs_mat vert <<'GLSL'
#version 450
layout(location = 0) in vec4 position;
layout(set = 0, binding = 0, std140) uniform M { layout(row_major) mat4 rm; layout(column_major) mat4 cm; int sel; };
void main() {
    if (sel == 0) gl_Position = rm * position;
    else gl_Position = cm * position;
}
GLSL
# the position moved by a texel: an image
shader vs_image vert <<'GLSL'
#version 450
layout(location = 0) in vec4 position;
layout(set = 0, binding = 1) uniform sampler2D tex;
void main() { gl_Position = position + textureLod(tex, vec2(0.5), 0.0); }
GLSL
# a branch on a value the run does not compute (a square root)
shader vs_branch vert <<'GLSL'
#version 450
layout(location = 0) in vec4 position;
void main() {
    if (sqrt(abs(position.x)) > 5.0) gl_Position = vec4(0.0);
    else gl_Position = position;
}
GLSL
# the shape of DXVK's D3D9 vertex shaders (dxbc-spirv, SSA): c0..c3 as the rows of a matrix in a
# block of vec4 members (dp4 oPos, v0, cN), a 16-bit push data member widened to 32 bits, a bit
# field of a specialization constant read in a function and branched on
shader vs_dxso vert ssa <<'GLSL'
#version 450
#extension GL_EXT_shader_16bit_storage : require
#extension GL_EXT_shader_explicit_arithmetic_types_int16 : require
layout(constant_id = 0) const uint commonState = 0u;
layout(location = 0) in vec4 v0;
layout(location = 1) in vec2 v1;
layout(set = 1, binding = 3, std140) uniform c_buf { vec4 c0; vec4 c1; vec4 c2; vec4 c3; vec4 c4; } c;
layout(push_constant) uniform push_data_t { uint16_t cFSize; uint16_t wScale; } pd;
layout(location = 0) out vec2 o0;
uint clipPlaneCount() { return bitfieldExtract(commonState, 0, 3); }
void main() {
    vec4 r0 = vec4(dot(v0, c.c0), dot(v0, c.c1), dot(v0, c.c2), dot(v0, c.c3));
    r0.w *= float(uint(pd.wScale));
    if (clipPlaneCount() != 0u) r0.z = r0.w;
    gl_Position = r0;
    o0 = v1 * c.c4.xy;
}
GLSL
shader fs_plain frag <<'GLSL'
#version 450
layout(binding = 1) uniform sampler2D tex;
layout(location = 0) in vec2 uv;
layout(location = 0) out vec4 color;
void main() { color = texture(tex, uv); }
GLSL
shader fs_discard frag <<'GLSL'
#version 450
layout(binding = 1) uniform sampler2D tex;
layout(location = 0) in vec2 uv;
layout(location = 0) out vec4 color;
void main() { color = texture(tex, uv); if (color.a < 0.5) discard; }
GLSL
# DXVK's D3D9 alpha test: a compare op from a specialization constant (7: always), read in a
# function, a demote when the test fails
shader fs_alpha frag ssa <<'GLSL'
#version 450
#extension GL_EXT_demote_to_helper_invocation : require
layout(constant_id = 0) const uint alphaTest = 0x77u;
layout(binding = 1) uniform sampler2D tex;
layout(location = 0) in vec2 uv;
layout(location = 0) out vec4 color;
uint compareOp() { return bitfieldExtract(alphaTest, 0, 3); }
void main() {
    color = texture(tex, uv);
    bool pass;
    switch (compareOp()) {
    case 7u: pass = true; break;
    case 0u: pass = false; break;
    default: pass = color.a >= 0.5; break;
    }
    if (!pass) demote;
}
GLSL
shader fs_mask frag <<'GLSL'
#version 450
layout(binding = 1) uniform sampler2D tex;
layout(location = 0) in vec2 uv;
layout(location = 0) out vec4 color;
void main() { color = texture(tex, uv); gl_SampleMask[0] = color.a < 0.5 ? 0 : 1; }
GLSL
shader cs_write comp <<'GLSL'
#version 450
layout(local_size_x = 1) in;
layout(binding = 0) buffer Out { uint words[]; };
void main() { words[gl_GlobalInvocationID.x] = 1u; }
GLSL
# reads the attachment's old contents (dynamic rendering local read)
shader fs_input frag <<'GLSL'
#version 450
layout(input_attachment_index = 0, set = 0, binding = 0) uniform subpassInput prev;
layout(location = 0) out vec4 color;
void main() { color = subpassLoad(prev) * 0.5; }
GLSL
# a kill reached through case 0 of a switch on a 64-bit constant (two words per case literal)
cat > "$T/fs_switch64.spvasm" <<'ASM'
               OpCapability Shader
               OpCapability Int64
               OpMemoryModel Logical GLSL450
               OpEntryPoint Fragment %main "main" %color
               OpExecutionMode %main OriginUpperLeft
               OpDecorate %color Location 0
       %void = OpTypeVoid
         %fn = OpTypeFunction %void
      %float = OpTypeFloat 32
    %v4float = OpTypeVector %float 4
      %ptr = OpTypePointer Output %v4float
      %color = OpVariable %ptr Output
       %long = OpTypeInt 64 1
     %long_0 = OpConstant %long 0
    %float_1 = OpConstant %float 1
        %one = OpConstantComposite %v4float %float_1 %float_1 %float_1 %float_1
       %main = OpFunction %void None %fn
      %entry = OpLabel
               OpStore %color %one
               OpSelectionMerge %merge None
               OpSwitch %long_0 %merge 0 %kill
       %kill = OpLabel
               OpKill
      %merge = OpLabel
               OpReturn
               OpFunctionEnd
ASM
spirv-as --target-env vulkan1.1 -o "$T/fs_switch64.spv" "$T/fs_switch64.spvasm"
python3 -c 'import struct,sys
w=open(sys.argv[1],"rb").read()
w=struct.unpack("<%dI"%(len(w)//4),w)
print("const uint32_t ls_%s[] = {"%sys.argv[2])
for i in range(0,len(w),8): print("\t"+",".join("0x%08x"%x for x in w[i:i+8])+",")
print("};")' "$T/fs_switch64.spv" fs_switch64 >> "$T/all.h"
mv "$T/all.h" load_skip_spv.h
