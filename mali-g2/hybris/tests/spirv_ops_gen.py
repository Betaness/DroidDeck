#!/usr/bin/env python3
# Regenerates src/spirv_ops.h from a SPIR-V C++ header (spirv.hpp, its HasResultAndType):
#   python3 tests/spirv_ops_gen.py app/src/main/cpp/thirdparty/dxbc/include/spirv/thirdparty/spirv.hpp > src/spirv_ops.h
import re
import sys

src = open(sys.argv[1]).read()
version = re.search(r'#define SPV_VERSION (0x[0-9a-fA-F]+)', src).group(1)
revision = re.search(r'Revision = (\d+);', src).group(1)
enum = {}
for m in re.finditer(r'^\s+Op(\w+) = (\d+),', src, re.M):
    enum.setdefault(m.group(1), int(m.group(2)))
start = src.index('inline void HasResultAndType')
body = src[start:src.index('\n}\n', start)]
ops = {}
for name, res, typ in re.findall(r'case Op(\w+): \*hasResult = (true|false); \*hasResultType = (true|false); break;', body):
    ops[enum[name]] = (res == 'true') << 1 | (typ == 'true')
print('/* Generated by tests/spirv_ops_gen.py from spirv.hpp (SPV_VERSION %s, revision %s): every opcode it' % (version, revision))
print(' * knows, (opcode << 2) | (has result id << 1) | has result type, sorted. */')
print('#ifndef DROIDDECK_SPIRV_OPS_H')
print('#define DROIDDECK_SPIRV_OPS_H')
print('#include <stdint.h>')
print('static const uint32_t spv_known_ops[] = {')
items = ['0x%x' % (op << 2 | f) for op, f in sorted(ops.items())]
for i in range(0, len(items), 12):
    print('    ' + ', '.join(items[i:i + 12]) + ',')
print('};')
print('#endif')
